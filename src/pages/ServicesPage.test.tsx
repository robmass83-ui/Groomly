// @vitest-environment happy-dom
import { render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { App } from '../app/App'
import { storageKeys } from '../data/local/storage'

async function openServices(user: ReturnType<typeof userEvent.setup>) {
  await user.click(screen.getByRole('button', { name: 'Non hai un account? Crea account' }))
  await user.type(screen.getByLabelText('Nome'), 'Maria')
  await user.type(screen.getByLabelText('Cognome'), 'Rossi')
  await user.type(screen.getByLabelText('Nome della toelettatura'), 'Il Cane Felice')
  await user.type(screen.getByLabelText('Email'), 'maria@salone.it')
  await user.type(screen.getByLabelText('Password'), 'segretissimo')
  await user.click(screen.getByRole('checkbox', { name: 'Accetto privacy e termini' }))
  await user.click(screen.getByRole('button', { name: 'Crea account' }))
  await screen.findByRole('heading', { name: 'Groomly' })
  await user.click(screen.getByRole('link', { name: /Impostazioni/ }))
  await user.click(screen.getByRole('link', { name: /Servizi e durate/ }))
  await screen.findByRole('heading', { name: 'Servizi e durate' })
}

describe('servizi', () => {
  beforeEach(() => localStorage.clear())

  it('modifica un extra, aggiunge un servizio e non offre elimina', async () => {
    const user = userEvent.setup()
    render(<App memory isDev={false} />)
    await openServices(user)
    expect(screen.queryByRole('button', { name: /Elimina/i })).not.toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Sposta su Bagno' })).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Riordina Bagno' })).toBeInTheDocument()
    const bagno = screen.getByRole('button', { name: 'Apri Bagno' })
    const bagnoStyle = bagno.getAttribute('style') ?? ''
    expect(bagnoStyle).toContain('display: flex')
    expect(bagnoStyle).toContain('flex-grow: 1')
    expect(bagnoStyle).toContain('min-width: 0')
    expect(bagnoStyle).toContain('gap: 8px')
    expect(bagnoStyle).not.toContain('min-height: 44')
    const nome = within(bagno).getByText('Bagno')
    expect(nome).not.toBe(bagno)
    const nomeStyle = nome.getAttribute('style') ?? ''
    expect(nomeStyle).toContain('overflow: hidden')
    expect(nomeStyle).toContain('text-overflow: ellipsis')
    expect(nomeStyle).toContain('white-space: nowrap')
    const meta = within(bagno).getByText('30–60 min · € 20–38')
    const metaStyle = meta.getAttribute('style') ?? ''
    expect(metaStyle).toContain('color: var(--tx3)')
    expect(metaStyle).toContain('font-size: 13px')
    expect(metaStyle).toContain('white-space: nowrap')
    expect(metaStyle).toContain('flex-grow: 0')
    expect(metaStyle).toContain('flex-shrink: 0')
    expect(metaStyle).toContain('flex-basis: auto')
    const chevron = bagno.querySelector('svg')
    expect(chevron).toHaveAttribute('width', '16')
    expect(chevron).toHaveAttribute('height', '16')
    expect(chevron).toHaveAttribute('stroke-width', '2')
    const interruttore = screen.getByRole('switch', { name: 'Bagno' })
    expect(bagno).not.toContainElement(interruttore)
    const row = bagno.closest('[data-service-row]') as HTMLElement
    expect(row).toContainElement(screen.getByRole('button', { name: 'Riordina Bagno' }))
    expect(row).toContainElement(screen.getByTestId('icon-Bagno'))
    expect(row).toContainElement(interruttore)
    const rowStyle = row.getAttribute('style') ?? ''
    expect(rowStyle).toContain('display: flex')
    expect(rowStyle).toContain('align-items: center')
    expect(rowStyle).toContain('gap: 8px')
    expect(rowStyle).toContain('min-height: 0')
    expect(rowStyle).not.toContain('min-height: 44')
    expect(rowStyle).not.toContain('flex-direction: column')
    expect(within(row).queryByText('30–60m')).not.toBeInTheDocument()
    expect(within(row).queryByText('€ 20–38')).not.toBeInTheDocument()
    expect(within(row).queryByText('Disattivato')).not.toBeInTheDocument()
    const principali = screen.getByRole('heading', { name: /Principali/ }).closest('section') as HTMLElement
    const extra = screen.getByRole('heading', { name: /^Extra/ }).closest('section') as HTMLElement
    const gestioneNodi = within(extra).getByRole('button', { name: 'Apri Gestione nodi' })
    expect(principali).toContainElement(bagno)
    expect(principali).not.toContainElement(gestioneNodi)
    expect(extra).toContainElement(gestioneNodi)
    expect(within(gestioneNodi).getByText('+20 min · € 5')).toBeInTheDocument()
    const aggiungi = screen.getByRole('button', { name: 'Aggiungi servizio' })
    expect(principali).not.toContainElement(aggiungi)
    expect(extra).not.toContainElement(aggiungi)
    await user.click(interruttore)
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    const spento = within(bagno).getByText('Spento')
    expect(spento.parentElement).toBe(bagno)
    expect(spento.getAttribute('style') ?? '').toContain('color: var(--tx3)')
    expect(spento.getAttribute('style') ?? '').not.toContain('border-radius')
    expect(within(bagno).getByText('Bagno').getAttribute('style')).toContain('color: var(--tx3)')
    expect(within(bagno).queryByText(/min/)).not.toBeInTheDocument()
    expect(screen.queryByText('Disattivato')).not.toBeInTheDocument()
    await user.click(interruttore)
    expect(within(bagno).getByText('30–60 min · € 20–38')).toBeInTheDocument()
    expect(within(bagno).queryByText('Spento')).not.toBeInTheDocument()
    await user.click(within(bagno).getByText('30–60 min · € 20–38'))
    expect(screen.getByRole('dialog', { name: 'Modifica servizio' })).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Chiudi' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Apri Gestione nodi' }))
    const price = screen.getByLabelText('Prezzo')
    await user.clear(price)
    await user.type(price, '9')
    await user.click(screen.getByRole('button', { name: 'Salva' }))
    expect(await screen.findByRole('status')).toHaveTextContent('Salvato')
    const raw = localStorage.getItem(storageKeys.services(JSON.parse(localStorage.getItem(storageKeys.auth)!).uid))!
    const nodi = JSON.parse(raw).nodi
    expect(nodi.price).toEqual({ piccola: 9, media: 9, grande: 9 })
    await user.click(screen.getByRole('button', { name: 'Aggiungi servizio' }))
    await user.type(screen.getByLabelText('Nome'), 'Spazzolata')
    await user.click(screen.getByRole('radio', { name: 'Extra' }))
    await user.type(screen.getByLabelText('Durata'), '10')
    await user.type(screen.getByLabelText('Prezzo'), '5')
    await user.click(screen.getByRole('button', { name: 'Salva' }))
    expect(await screen.findByText('Spazzolata')).toBeInTheDocument()
    expect(within(screen.getByTestId('icon-Spazzolata')).getByTestId('service-fallback')).toBeInTheDocument()
  }, 20000)

  it('se la scrittura fallisce lascia il nome precedente', async () => {
    const user = userEvent.setup()
    render(<App memory isDev={false} />)
    await openServices(user)
    await user.click(screen.getByRole('button', { name: 'Apri Bagno' }))
    const name = screen.getByLabelText('Nome')
    await user.clear(name)
    await user.type(name, 'Bagno nuovo')
    vi.spyOn(localStorage, 'setItem').mockImplementation(() => {
      throw new Error('quota')
    })
    await user.click(screen.getByRole('button', { name: 'Salva' }))
    expect(await screen.findByRole('status')).toHaveTextContent('Salvataggio non riuscito')
    const dialog = screen.getByRole('dialog', { name: 'Modifica servizio' })
    expect(within(dialog).queryByTestId('sheet-grabber')).not.toBeInTheDocument()
    expect(dialog.parentElement?.getAttribute('style')).toContain('align-items: center')
    vi.restoreAllMocks()
    expect(screen.getByRole('button', { name: 'Apri Bagno' })).toBeInTheDocument()
  })

  it('ArrowDown su un principale non ultimo permuta il gruppo e non tocca gli extra', async () => {
    const user = userEvent.setup()
    render(<App memory isDev={false} />)
    await openServices(user)
    const handle = screen.getByRole('button', { name: 'Riordina Bagno' })
    handle.focus()
    await user.keyboard('{ArrowDown}')
    const uid = JSON.parse(localStorage.getItem(storageKeys.auth)!).uid as string
    const raw = JSON.parse(localStorage.getItem(storageKeys.services(uid))!) as Record<string, { id: string; kind: string; order: number }>
    const principali = Object.values(raw).filter((item) => item.kind === 'principale').sort((a, b) => a.order - b.order)
    expect(principali.map((item) => item.id)).toEqual(['taglio', 'bagno', 'bagno-taglio', 'stripping'])
    const extras = Object.values(raw).filter((item) => item.kind === 'extra')
    expect(extras.map((item) => item.order).sort((a, b) => a - b)).toEqual([4, 5, 6, 7])
  })
  it('elimina un servizio dalla scheda dopo la conferma', async () => {
    const user = userEvent.setup()
    render(<App memory isDev={false} />)
    await openServices(user)
    await user.click(screen.getByRole('button', { name: 'Apri Unghie' }))
    await user.click(await screen.findByRole('button', { name: 'Elimina servizio' }))
    expect(await screen.findByText('Eliminare «Unghie»?')).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Annulla' }))
    expect(screen.getByRole('button', { name: 'Apri Unghie' })).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Apri Unghie' }))
    await user.click(await screen.findByRole('button', { name: 'Elimina servizio' }))
    await user.click(await screen.findByRole('button', { name: 'Elimina servizio' }))
    expect(screen.queryByRole('button', { name: 'Apri Unghie' })).not.toBeInTheDocument()
    const key = Object.keys(localStorage).find((item) => item.includes('services')) ?? ''
    const stored = Object.values(JSON.parse(localStorage.getItem(key) ?? '{}') as Record<string, { name: string }>)
    expect(stored.some((service) => service.name === 'Unghie')).toBe(false)
  })

  it('una scheda nuova non offre Elimina servizio', async () => {
    const user = userEvent.setup()
    render(<App memory isDev={false} />)
    await openServices(user)
    await user.click(screen.getByRole('button', { name: 'Aggiungi servizio' }))
    await screen.findByRole('button', { name: 'Salva' })
    expect(screen.queryByRole('button', { name: 'Elimina servizio' })).not.toBeInTheDocument()
  })
})
